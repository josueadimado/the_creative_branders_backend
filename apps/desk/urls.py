"""Addresses for the studio desk. All of them sit under /api/desk/."""
from django.urls import path

from .views import (
    AcademyListView,
    DeskLoginView,
    DeskLogoutView,
    DeskMeView,
    InquiryDetailView,
    InquiryListView,
    NewsletterListView,
    NoteDetailView,
    NoteListView,
    OverviewView,
    PageDetailView,
    PageListView,
    ProjectDetailView,
    ProjectListView,
    ProjectLogoView,
    SettingsView,
    ShotDetailView,
    ShotListView,
    WaitlistListView,
)

urlpatterns = [
    path("login/", DeskLoginView.as_view(), name="desk-login"),
    path("logout/", DeskLogoutView.as_view(), name="desk-logout"),
    path("me/", DeskMeView.as_view(), name="desk-me"),
    path("overview/", OverviewView.as_view(), name="desk-overview"),
    path("pages/", PageListView.as_view(), name="desk-pages"),
    path("pages/<slug:slug>/", PageDetailView.as_view(), name="desk-page"),
    path("projects/", ProjectListView.as_view(), name="desk-projects"),
    path("projects/<int:pk>/", ProjectDetailView.as_view(), name="desk-project"),
    path("projects/<int:pk>/logo/", ProjectLogoView.as_view(), name="desk-project-logo"),
    path("projects/<int:pk>/shots/", ShotListView.as_view(), name="desk-shots"),
    path("shots/<int:pk>/", ShotDetailView.as_view(), name="desk-shot"),
    path("notes/", NoteListView.as_view(), name="desk-notes"),
    path("notes/<int:pk>/", NoteDetailView.as_view(), name="desk-note"),
    path("settings/", SettingsView.as_view(), name="desk-settings"),
    path("inquiries/", InquiryListView.as_view(), name="desk-inquiries"),
    path("inquiries/<int:pk>/", InquiryDetailView.as_view(), name="desk-inquiry"),
    path("waitlist/", WaitlistListView.as_view(), name="desk-waitlist"),
    path("waitlist/<int:pk>/", WaitlistListView.as_view(), name="desk-waitlist-one"),
    path("newsletter/", NewsletterListView.as_view(), name="desk-newsletter"),
    path("newsletter/<int:pk>/", NewsletterListView.as_view(), name="desk-newsletter-one"),
    path("academy/", AcademyListView.as_view(), name="desk-academy"),
    path("academy/<int:pk>/", AcademyListView.as_view(), name="desk-academy-one"),
]
